CREATE TABLE kcv_dataset_runs (
    run_id VARCHAR2(32) PRIMARY KEY, status VARCHAR2(16) NOT NULL,
    phase VARCHAR2(128) NOT NULL, source_ref VARCHAR2(40) NOT NULL,
    manifest_sha256 VARCHAR2(64) NOT NULL, dataset_id VARCHAR2(64),
    graph_name VARCHAR2(128), started_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE, error_code NUMBER,
    CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')))
